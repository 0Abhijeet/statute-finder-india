"""Schema. Provenance (addendum) is captured at parse time and stored on the
section row: source file + hash, page range, char offsets, and a `segments` list
that lets a citation be re-verified against the file. Versioning fields are
columns on `acts`; no exact-date logic exists yet (Phase 4)."""
import datetime as dt

from pgvector.sqlalchemy import Vector
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy import (
    JSON, Column, Computed, Date, DateTime, ForeignKey, Index, Integer, String, Text, UniqueConstraint,
)

from src.database import Base

EMBEDDING_DIM = 384  # also in the migration; changing it needs a new migration + re-ingest


class Act(Base):
    __tablename__ = "acts"
    id = Column(Integer, primary_key=True)
    short_name = Column(String(64), nullable=False, unique=True)   # e.g. "bns_2023"
    title = Column(String(255), nullable=False)
    year = Column(Integer, nullable=False)
    jurisdiction = Column(String(32), nullable=False)             # "central" | "tamil_nadu"
    version_note = Column(Text)
    effective_from = Column(Date)       # NULL until verified from an official source (Phase 4)
    effective_to = Column(Date)
    superseded_by = Column(Integer, ForeignKey("acts.id"))


class SourceFile(Base):
    __tablename__ = "source_files"
    id = Column(Integer, primary_key=True)
    act_id = Column(Integer, ForeignKey("acts.id"))
    filename = Column(String(255), nullable=False)
    sha256 = Column(String(64), nullable=False, unique=True)
    source_url = Column(Text, nullable=False)
    retrieved_at = Column(DateTime(timezone=True), nullable=False)
    page_count = Column(Integer, nullable=False)
    role = Column(String(16), nullable=False)                      # corpus | mapping


class Section(Base):
    __tablename__ = "sections"
    id = Column(Integer, primary_key=True)
    act_id = Column(Integer, ForeignKey("acts.id", ondelete="CASCADE"), nullable=False)
    source_file_id = Column(Integer, ForeignKey("source_files.id"), nullable=False)
    anchor = Column(String(96), nullable=False, unique=True)       # "bns_2023:s103"
    number = Column(String(16), nullable=False)                    # "103", "4A"
    title = Column(Text)
    title_source = Column(String(32))                              # "act_text" | NULL
    chapter = Column(String(16))
    chapter_title = Column(Text)
    status = Column(String(16), nullable=False, default="in_force")  # in_force | omitted
    text = Column(Text, nullable=False)                            # exact text from the PDF
    page_start = Column(Integer, nullable=False)                   # 1-indexed
    page_end = Column(Integer, nullable=False)
    char_start = Column(Integer, nullable=False)                   # offset in page_start's text
    char_end = Column(Integer, nullable=False)                     # offset in page_end's text
    segments = Column(JSON, nullable=False)                        # [{"page","start","end"}, ...]
    __table_args__ = (UniqueConstraint("act_id", "number", name="uq_section_act_number"),)


class Chunk(Base):
    __tablename__ = "chunks"
    id = Column(Integer, primary_key=True)
    section_id = Column(Integer, ForeignKey("sections.id", ondelete="CASCADE"), nullable=False)
    chunk_no = Column(Integer, nullable=False)
    header = Column(Text, nullable=False)       # embedded with the text; never shown as the quote
    text = Column(Text, nullable=False)         # == section.text[char_start:char_end]
    char_start = Column(Integer, nullable=False)   # offsets within section.text
    char_end = Column(Integer, nullable=False)
    embedding = Column(Vector(EMBEDDING_DIM), nullable=False)
    # Keyword leg (decision 25). Generated by Postgres; added by migration 0002.
    fts = Column(
        TSVECTOR,
        Computed("to_tsvector('english', coalesce(header, '') || ' ' || coalesce(text, ''))", persisted=True),
    )
    __table_args__ = (UniqueConstraint("section_id", "chunk_no", name="uq_chunk_section_no"),)


Index("ix_chunks_section_id", Chunk.section_id)
Index("ix_chunks_fts", Chunk.fts, postgresql_using="gin")
Index("ix_sections_act_id", Section.act_id)


class IpcBnsMapping(Base):
    __tablename__ = "ipc_bns_mapping"
    id = Column(Integer, primary_key=True)
    source_file_id = Column(Integer, ForeignKey("source_files.id"), nullable=False)
    bns_ref = Column(String(32), nullable=False)       # "85", "2(2)", "326(a)"
    bns_section = Column(Integer, nullable=False)
    subject = Column(Text, nullable=False)
    ipc_ref = Column(String(64), nullable=False)       # "498A", "428/ 429", "-", ...
    summary = Column(Text, nullable=False)
    page = Column(Integer, nullable=False)             # 1-indexed page of the comparison PDF


Index("ix_mapping_bns_section", IpcBnsMapping.bns_section)


class ProvisionStatus(Base):
    """Curated legal-status flags (decision 40); seeded from data/provision_status.json."""
    __tablename__ = "provision_status"
    id = Column(Integer, primary_key=True)
    act_short_name = Column(String(64), nullable=False)
    section = Column(String(16), nullable=False)
    status = Column(String(32), nullable=False)          # struck_down | not_in_force
    scope = Column(Text, nullable=False)
    note = Column(Text, nullable=False)
    source_url = Column(Text, nullable=False)
    source_label = Column(Text, nullable=False)
    verification = Column(String(32), nullable=False)    # source_located | third_party_only
    __table_args__ = (UniqueConstraint("act_short_name", "section", name="uq_status_act_section"),)
